    private void loadExitHistory() {
        try {
            String animalId = jLabel2.getText();
            ResultSet resultSet = MySQL.executeSearch("SELECT * FROM `animal_exit` WHERE `animal_id` = '" + animalId + "'");

            DefaultTableModel model = (DefaultTableModel) jTable2.getModel();
            model.setRowCount(0);

            while (resultSet.next()) {

                Vector<String> vector = new Vector<>();
                vector.add(resultSet.getString("exit_date"));
                vector.add(resultSet.getString("exit_location"));
                vector.add(resultSet.getString("exit_reason"));

                model.addRow(vector);
            }
            jTable2.setModel(model);

        } catch (Exception e) {
            e.printStackTrace();
        }
    }

    private void loadReturnHistory() {
        try {
            String animalId = jLabel2.getText();
            ResultSet resultSet = MySQL.executeSearch("SELECT * FROM `animal_return` WHERE `animal_id` = '" + animalId + "'");

            DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
            model.setRowCount(0);

            while (resultSet.next()) {

                Vector<String> vector = new Vector<>();
                vector.add(resultSet.getString("return_date"));
                vector.add(resultSet.getString("return_reason"));

                model.addRow(vector);
            }
            jTable1.setModel(model);

        } catch (Exception e) {
            e.printStackTrace();
        }
    }

