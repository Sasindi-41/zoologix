    private void loadKeepers() {
        try {
            String query = "SELECT * FROM `user`"
                    + "INNER JOIN `usertype` ON `user`.`usertype_id` = `usertype`.`id` "
                    + "INNER JOIN `userstatus` ON `user`.`userstatus_id` = `userstatus`.`id` "
                    + "INNER JOIN `gender` ON `user`.`gender_id` = `gender`.`id` WHERE `usertype_id` = 1 AND `userstatus_id` = 1 ";
                    
            String sort = String.valueOf(jComboBox1.getSelectedItem());
            
            query += "ORDER BY ";


            if (sort.equals("Keeper ID ASC")) {
                query += "`user`.`id` ASC";
            } else if (sort.equals("Keeper ID DESC")) {
                query += "`user`.`id` DESC";
            } else if (sort.equals("Keeper Name ASC")) {
                query += "`user`.`fname` ASC";
            } else if (sort.equals("Keeper Name DESC")) {
                query += "`user`.`fname` DESC";
            } else if (sort.equals("Gender ASC")) {
                query += "`gender`.`name` ASC";
            } else if (sort.equals("Gender DESC")) {
                query += "`gender`.`name` DESC";
            }

            ResultSet resultSet = MySQL.executeSearch(query);         

            DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
            model.setRowCount(0);

            while (resultSet.next()) {

                Vector<String> vector = new Vector<>();
                vector.add(resultSet.getString("id"));
                vector.add(resultSet.getString("fname"));
                vector.add(resultSet.getString("lname"));
                vector.add(resultSet.getString("mobile"));
                vector.add(resultSet.getString("email"));
                vector.add(resultSet.getString("gender.name"));

                model.addRow(vector);
            }
            jTable1.setModel(model);

        } catch (Exception e) {
            e.printStackTrace();
        }
    }

