    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        
        String year = jTextField1.getText();
        
        if (year.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter year", "Warning", JOptionPane.WARNING_MESSAGE);
        }else if(!year.matches("^[1-9][0-9]*$")){
            JOptionPane.showMessageDialog(this, "Please enter valid year", "Warning", JOptionPane.WARNING_MESSAGE);
        }else{
            
            try {
                ResultSet rs = MySQL.executeSearch("SELECT * FROM `year` WHERE `year` = '"+year+"' ");
                if (rs.next()) {
                     JOptionPane.showMessageDialog(this, "Year already added", "Warning", JOptionPane.WARNING_MESSAGE);
                }else{
                
                    MySQL.executeIUD("INSERT INTO `year` (`year`) VALUES ('"+year+"') ");
                    JOptionPane.showMessageDialog(this, "Year added success", "Success", JOptionPane.INFORMATION_MESSAGE);
                    loadyears();
                    reset();
                }
            } catch (Exception e) {
                 logger.log(java.util.logging.Level.WARNING, "Exception Occured", e);
            }
        
        }
    }//GEN-LAST:event_jButton1ActionPerformed

