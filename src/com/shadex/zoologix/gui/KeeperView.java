    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        if (evt.getClickCount() == 2) {
            
            int row = jTable1.getSelectedRow();
            String id = String.valueOf(jTable1.getValueAt(row, 0));
            String fname = String.valueOf(jTable1.getValueAt(row, 1));
            String lname = String.valueOf(jTable1.getValueAt(row, 2));
            String mobile = String.valueOf(jTable1.getValueAt(row, 3));
            String email = String.valueOf(jTable1.getValueAt(row, 4));

            if (keeper == "Keeper1") {
                 animalregistration.setKeepername(fname+" "+lname);
                 animalregistration.setKeeperID(id);
                 animalregistration.setKeeperMobile(mobile);
                 animalregistration.setKeeperEmail(email);
            }else  if (keeper == "Keeper3") {
                 breedingevents.setKeeperDetails(id);
            }else  if (keeper == "Keeper4") {
                 enclosureRegistration.setKeaperDetails(id);
            }
            
           this.dispose();

       }
    }//GEN-LAST:event_jTable1MouseClicked

    private void jTextField4KeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_jTextField4KeyReleased
        String searchText = jTextField4.getText().toLowerCase();

        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();

        TableRowSorter<DefaultTableModel> sorter = new TableRowSorter<>(model);

        jTable1.setRowSorter(sorter);

        sorter.setRowFilter(RowFilter.regexFilter(searchText));
        loadKeepers();
    }//GEN-LAST:event_jTextField4KeyReleased

