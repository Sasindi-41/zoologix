    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
       
        String username = jTextField1.getText();
        String password = String.valueOf(jPasswordField1.getPassword());
        
        if (username.isEmpty()) {
             JOptionPane.showMessageDialog(this, "Please Enter Email", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if(password.isEmpty()){
            JOptionPane.showMessageDialog(this, "Please Enter Password", "Warning", JOptionPane.WARNING_MESSAGE);
        }else{
            
            try {
                
                ResultSet resultSet  = MySQL.executeSearch("SELECT * FROM `user` WHERE `email` = '"+username+"' AND `password` = '"+password+"' ");
                if (resultSet.next()) {
                    
                     Dashboard dashboard = new Dashboard(username);
                      dashboard.setVisible(true);
                     this.dispose();
                    
                }else{
                
                    JOptionPane.showMessageDialog(this, "Username or Password does not match", "Warning", JOptionPane.WARNING_MESSAGE);
                }
            } catch (Exception e) {
                 logger.log(java.util.logging.Level.WARNING, "Exception Occured", e);
            }
            

        }
    }//GEN-LAST:event_jButton1ActionPerformed

  
