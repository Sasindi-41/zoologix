    private void loadBreedingDetails(){
        String breedingId = jLabel2.getText();
        try {
            
            ResultSet rs = MySQL.executeSearch("SELECT * FROM `breeding_events` "
                    + "INNER JOIN `pregnancy_status` ON `breeding_events`.`pregnancy_status_id` = `pregnancy_status`.`id` "
                    + "INNER JOIN `animal` AS `animal_male` ON `breeding_events`.`animal_id_male` = `animal_male`.`id` "
                    + "INNER JOIN `animal` AS `animal_female` ON `breeding_events`.`animal_id_female` = `animal_female`.`id` "
                    + "INNER JOIN `user` AS `keeper` ON `breeding_events`.`user_id_keeper` = `keeper`.`id` "
                    + "INNER JOIN `user` AS `vet` ON `breeding_events`.`user_id_vet` = `vet`.`id`");
            
            if (rs.next()) {
                jLabel5.setText(rs.getString("animal_male.id"));
                jLabel7.setText(rs.getString("animal_male.name"));
                jLabel6.setText(rs.getString("animal_female.id"));
                jLabel8.setText(rs.getString("animal_female.name"));
                jLabel12.setText(rs.getString("breeding_date"));
                jLabel13.setText(rs.getString("pregnancy_status.status"));
                jLabel14.setText(rs.getString("offspring_count"));
                
                jLabel26.setText(rs.getString("keeper.id"));
                jLabel27.setText(rs.getString("keeper.fname") + " " + rs.getString("keeper.lname"));
                jLabel29.setText(rs.getString("keeper.mobile"));
                jLabel28.setText(rs.getString("keeper.email"));
                
                jLabel32.setText(rs.getString("vet.id"));
                jLabel34.setText(rs.getString("vet.fname") + " " + rs.getString("vet.lname"));
                jLabel33.setText(rs.getString("vet.mobile"));
                jLabel35.setText(rs.getString("vet.email"));
                                
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
        
    }
