    private void loadAnimalDetails(){
        String animalId = jLabel1.getText();
        try {
            
            ResultSet rs = MySQL.executeSearch("SELECT * FROM `offspring_born` "
                    + "INNER JOIN `health_status` ON `offspring_born`.`health_status_id` = `health_status`.`id` "
                    + "INNER JOIN `enclosure` ON `offspring_born`.`enclosure_id` = `enclosure`.`id` "
                    + "INNER JOIN `gender` ON `offspring_born`.`gender_id` = `gender`.`id` "
                    + "INNER JOIN `native_region` ON `offspring_born`.`native_region_id` = `native_region`.`id` "
                    + "INNER JOIN `animal_category` ON `offspring_born`.`animal_category_id` = `animal_category`.`id` "
                    + "INNER JOIN `iucn_category` ON `offspring_born`.`iucn_category_id` = `iucn_category`.`id` "
                    + "INNER JOIN `user` ON `offspring_born`.`user_id` = `user`.`id` "
                    + "INNER JOIN `breeding_events` ON `offspring_born`.`breeding_events_id` = `breeding_events`.`id` "
                    + "WHERE `offspring_born`.`id` = '"+animalId+"' ");
            
            if (rs.next()) {
                jLabel2.setText(rs.getString("name"));
                jLabel4.setText(rs.getString("scientific_name"));
                jLabel6.setText(rs.getString("date_of_birth"));
                jLabel8.setText(rs.getString("breeding_events.id"));
                jLabel13.setText(rs.getString("animal_count"));
                jTextArea1.setEditable(false);
                jTextArea1.setText(rs.getString("description"));
                jLabel15.setText(rs.getString("health_status.status"));
                jLabel17.setText(rs.getString("gender.name"));
                jLabel18.setText(rs.getString("native_region.name"));
                jLabel20.setText(rs.getString("animal_category.category"));
                jLabel22.setText(rs.getString("iucn_category.category"));
                jLabel24.setText(rs.getString("enclosure.name"));
                jLabel26.setText(rs.getString("user.id"));
                jLabel27.setText(rs.getString("user.fname") + " " + rs.getString("user.lname"));
                jLabel29.setText(rs.getString("user.mobile"));
                jLabel28.setText(rs.getString("user.email"));
                
            }
        } catch (Exception e) {
             logger.log(java.util.logging.Level.WARNING, "Exception Occured", e);
        }
        
    }
