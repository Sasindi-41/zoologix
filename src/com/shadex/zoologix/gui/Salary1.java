        private void calOT(int totalHours, double rate) {
        double baseSalary = Double.valueOf(jTextField1.getText());
        double salaryPerHour = (baseSalary / 20) / 8;
        double salaryPerHourWithOT = salaryPerHour * rate;
        double otAmount = salaryPerHourWithOT * totalHours;
        DecimalFormat df_obj = new DecimalFormat("#.##");
        jTextField4.setText(String.valueOf(df_obj.format(otAmount)));

    }
     
   

