    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        jButton1.setEnabled(false);
        int row = jTable1.getSelectedRow();

        String temperature = String.valueOf(jTable1.getValueAt(row, 1));
        jTextField1.setText(temperature);

        String humidity = String.valueOf(jTable1.getValueAt(row, 2));
        jTextField2.setText(humidity);

        String lighting = String.valueOf(jTable1.getValueAt(row, 3));
        jTextField3.setText(lighting);

        String airquality = String.valueOf(jTable1.getValueAt(row, 4));
        jTextField4.setText(airquality);

        String waterquality = String.valueOf(jTable1.getValueAt(row, 5));
        jTextField5.setText(waterquality);

        if (evt.getClickCount() == 2) {

            int row1 = jTable1.getSelectedRow();
            String efid = String.valueOf(jTable1.getValueAt(row1, 0));

            if (environmentalFacters == "ef1") {
                enclosureRegistration.setEnvironmentalFactors(efid);
            }

            this.dispose();

        }
    }//GEN-LAST:event_jTable1MouseClicked

