    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        
        String name = jTextField1.getText();
        String price = jTextField2.getText();

        if (name.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter a name", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (price.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter a price", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (!price.matches("\\d+(\\.\\d{1,2})?")) {  // Check if price is a valid number with up to two decimal places
            JOptionPane.showMessageDialog(this, "Please enter a valid number for the price", "Warning", JOptionPane.WARNING_MESSAGE);
        } else {
            try {
                ResultSet rs = MySQL.executeSearch("SELECT * FROM `ticket_price` WHERE `Name` = '" + name + "'");

                if (rs.next()) {
                    JOptionPane.showMessageDialog(this, "Ticket already registered", "Warning", JOptionPane.WARNING_MESSAGE);
                } else {
                    MySQL.executeIUD("INSERT INTO `ticket_price` (`Name`, `Price`) VALUES('" + name + "', '" + price + "')");
                    JOptionPane.showMessageDialog(this, "Ticket registered successfully", "Info", JOptionPane.INFORMATION_MESSAGE);
                    loadTicket();
                }
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Error: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        }

    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        String name = jTextField1.getText();
        String price = jTextField2.getText();

        if (price.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter a price", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (!price.matches("\\d+(\\.\\d{1,2})?")) {  // Check if price is a valid number with up to two decimal places
            JOptionPane.showMessageDialog(this, "Please enter a valid number for the price", "Warning", JOptionPane.WARNING_MESSAGE);
        } else {
            try {
                ResultSet rs = MySQL.executeSearch("SELECT * FROM `ticket_price` WHERE `Name` = '" + name + "' AND `Price` = '" + price + "'");

                if (rs.next()) {
                    JOptionPane.showMessageDialog(this, "Ticket price is already registered", "Warning", JOptionPane.WARNING_MESSAGE);
                } else {
                    MySQL.executeIUD("UPDATE `ticket_price` SET `Price` = '" + price + "' WHERE `Name` = '" + name + "'");
                    JOptionPane.showMessageDialog(this, "Ticket price updated successfully", "Info", JOptionPane.INFORMATION_MESSAGE);
                    loadTicket();
                    clearAll();
                }
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Error: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void loadTicket() {

        try {
            ResultSet resultSet = MySQL.executeSearch("SELECT * FROM `ticket_price`");

            DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
            model.setRowCount(0);
            while (resultSet.next()) {
                Vector<String> vector = new Vector<>();
                vector.add(resultSet.getString("name"));
                vector.add(resultSet.getString("price"));

                model.addRow(vector);
            }
        } catch (Exception e) {
             logger.log(java.util.logging.Level.WARNING, "Exception Occured", e);
        }
    }

    private void clearAll() {
        jTextField1.setText("");
        jTextField2.setText("");
        jTable1.clearSelection();
        jButton1.setEnabled(true);
        jTextField1.setEditable(true);
    }
