    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        int row = jTable1.getSelectedRow();

        if (row != -1) {
            String fName = jTextField1.getText();
            String lName = jTextField2.getText();
            String mobile = jTextField3.getText();
            String email = jTextField4.getText();

            if (fName.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please enter your First Name", "Warning", JOptionPane.WARNING_MESSAGE);
            } else if (lName.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please enter your First Name", "Warning", JOptionPane.WARNING_MESSAGE);
            } else if (validateMobile(mobile)) {
                return;
            } else if (validateEmail(email)) {

                return;
            } else {

                try {

                    ResultSet resultSet = MySQL.executeSearch("SELECT * FROM `supplier` WHERE `mobile` = '" + mobile + "' OR `email` = '" + email + "'");
                    boolean canUpdate = false;

                    if (resultSet.next()) {
                        if (!(resultSet.getString("email").equals(email))) {
                            JOptionPane.showMessageDialog(this, "This email or mobile already used", "Warning", JOptionPane.WARNING_MESSAGE);
                       
                        } else {
                            canUpdate = true;
                            JOptionPane.showMessageDialog(this, "This email or mobile already used", "Warning", JOptionPane.WARNING_MESSAGE);
                        }
                    } else {
                        canUpdate = true;
                        
                    }

                    if (canUpdate) {

                        MySQL.executeIUD("UPDATE `supplier` SET `fname` = '" + fName + "', `lname` = '" + lName + "',`email` = '" + email + "' WHERE `mobile` = '" + mobile + "' ");

                        loadSupplier();
                        reset();
                    }

                } catch (Exception e) {
                     logger.log(java.util.logging.Level.WARNING, "Exception Occured", e);
                }

            }
        }
    }//GEN-LAST:event_jButton4ActionPerformed

