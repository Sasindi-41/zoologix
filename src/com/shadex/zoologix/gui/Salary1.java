       private void calSalary() {
        double salary = 0;
        String basicSalary = jTextField1.getText();

        if (basicSalary.isEmpty() || basicSalary.equals("0")) {
            JOptionPane.showMessageDialog(this, "Please enter salary", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (!String.valueOf(basicSalary).matches("^\\d+(\\.\\d+)?$")) {
            JOptionPane.showMessageDialog(this, "Invalid amount", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (!jTextField2.getText().matches("^\\d+(\\.\\d+)?$")) {
            JOptionPane.showMessageDialog(this, "Invalid amount", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (!jTextField3.getText().matches("^\\d+(\\.\\d+)?$")) {
            JOptionPane.showMessageDialog(this, "Invalid amount", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (!jTextField6.getText().matches("^\\d+(\\.\\d+)?$")) {
            JOptionPane.showMessageDialog(this, "Invalid amount", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (!jTextField5.getText().matches("^\\d+(\\.\\d+)?$")) {
            JOptionPane.showMessageDialog(this, "Invalid amount", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (!jTextField4.getText().matches("^\\d+(\\.\\d+)?$")) {
            JOptionPane.showMessageDialog(this, "Invalid amount", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (!jTextField7.getText().matches("^\\d+(\\.\\d+)?$")) {
            JOptionPane.showMessageDialog(this, "Invalid amount", "Warning", JOptionPane.WARNING_MESSAGE);
        } else {
            double epf = (Double.parseDouble(basicSalary) / 100) * 8;
            DecimalFormat df_obj = new DecimalFormat("#.##");
            jTextField3.setText(String.valueOf(df_obj.format(epf)));

            salary += Double.valueOf(basicSalary);
            salary += Double.valueOf(jTextField2.getText());
            salary -= Double.valueOf(jTextField3.getText());

            if (jCheckBox1.isSelected()) {
                if (!jTextField6.getText().equals("0")) {
                    calOT(Integer.parseInt(jTextField6.getText()), Double.parseDouble(jTextField5.getText()));
                }

                salary += Double.valueOf(jTextField4.getText());
            }
            jTextField7.setText(String.valueOf(salary));
        }

    }
   
