    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        int row = jTable1.getSelectedRow();

        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Please Select to Update", "Warning", JOptionPane.WARNING_MESSAGE);
        } else {

            String id = String.valueOf(jTable1.getValueAt(row, 0));
            try {
                String temperature = jTextField1.getText();
                String humidity = jTextField2.getText();
                String lighting = jTextField3.getText();
                String airquality = jTextField4.getText();
                String waterquality = jTextField5.getText();

                if (temperature.isEmpty()) {
                    JOptionPane.showMessageDialog(this, "Please Enter Temperature", "Warning", JOptionPane.WARNING_MESSAGE);
                } else if (humidity.isEmpty()) {
                    JOptionPane.showMessageDialog(this, "Please Enter Humidity", "Warning", JOptionPane.WARNING_MESSAGE);
                } else if (lighting.isEmpty()) {
                    JOptionPane.showMessageDialog(this, "Please Enter Lighting", "Warning", JOptionPane.WARNING_MESSAGE);
                } else if (airquality.isEmpty()) {
                    JOptionPane.showMessageDialog(this, "Please Enter Air Quality", "Warning", JOptionPane.WARNING_MESSAGE);
                } else if (waterquality.isEmpty()) {
                    JOptionPane.showMessageDialog(this, "Please Enter Water Quality", "Warning", JOptionPane.WARNING_MESSAGE);
                } else {
                    boolean isFound = false;
                    for (int i = 0; i < jTable1.getRowCount(); i++) {
                        String getEFID = String.valueOf(jTable1.getValueAt(i, 0));
                        String getTemperature = String.valueOf(jTable1.getValueAt(i, 1));
                        String getHumidity = String.valueOf(jTable1.getValueAt(i, 2));
                        String getLighting = String.valueOf(jTable1.getValueAt(i, 3));
                        String getAirquality = String.valueOf(jTable1.getValueAt(i, 4));
                        String getWaterquality = String.valueOf(jTable1.getValueAt(i, 5));

                        if (getTemperature.equals(temperature) && getHumidity.equals(humidity) && getLighting.equals(lighting)
                                && getAirquality.equals(airquality) && getWaterquality.equals(waterquality)) {
                            JOptionPane.showMessageDialog(this, "This Environmental Factors are already added", "Warning", JOptionPane.WARNING_MESSAGE);
                            isFound = true;
                            break;
                        }

                    }
                    if (!isFound) {
                        MySQL.executeIUD("UPDATE `environmental_factors` SET `temperature` = '" + temperature + "',`humidity` = '" + humidity + "',"
                                + "`lighting` = '" + lighting + "',`air_quality` = '" + airquality + "',`water_quality` = '" + waterquality + "' WHERE `environmental_factors`.`id` = '" + id + "'");

                        reset();
                        loadEnvironmentalFacters();
                    }
                }
            } catch (Exception e) {
                e.printStackTrace();
            }
        }
    }//GEN-LAST:event_jButton2ActionPerformed

