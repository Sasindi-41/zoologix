    private void loadEnvironmentalFacters() {
        try {
            ResultSet resultSet = MySQL.executeSearch("SELECT * FROM `environmental_factors`");

            DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
            model.setRowCount(0);

            while (resultSet.next()) {

                Vector<String> vector = new Vector<>();
                vector.add(resultSet.getString("id"));
                vector.add(resultSet.getString("temperature"));
                vector.add(resultSet.getString("humidity"));
                vector.add(resultSet.getString("lighting"));
                vector.add(resultSet.getString("air_quality"));
                vector.add(resultSet.getString("water_quality"));

                model.addRow(vector);
            }
            jTable1.setModel(model);

        } catch (Exception e) {
            e.printStackTrace();
        }
    }

